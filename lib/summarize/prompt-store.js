/**
 * 取生效的 system prompt：override 非空（trim 后）则用它，否则用内置默认。
 */
export function getSystemPrompt(override) {
  const text = String(override == null ? '' : override).trim()
  return text || DEFAULT_SYSTEM_PROMPT
}

/** 与内置默认逐字比较（不做 trim），供设置页判断当前是否已自定义。 */
export function isDefaultPrompt(text) {
  return String(text == null ? '' : text) === DEFAULT_SYSTEM_PROMPT
}

/** 取生效的精细版 system prompt：语义与 getSystemPrompt 一致。 */
export function getDetailSystemPrompt(override) {
  const text = String(override == null ? '' : override).trim()
  return text || DEFAULT_DETAIL_SYSTEM_PROMPT
}

/** 与精细版内置默认逐字比较（不做 trim）。 */
export function isDefaultDetailPrompt(text) {
  return String(text == null ? '' : text) === DEFAULT_DETAIL_SYSTEM_PROMPT
}
